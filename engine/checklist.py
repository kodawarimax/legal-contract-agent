@dataclass(frozen=True)
class CommentViolation:
    """相手向けコメントで検出したv3違反。"""

    comment_index: int
    code: str
    phrase: str


_COMMENT_FORBIDDEN = {
    "M8": re.compile(r"(?:G社|Ｇ社|N社|Ｎ社|[○〇]+[^、。]{0,8}?\s*氏)"),
    "M13": re.compile(
        r"(?:当初(?:の)?案|即時解除案|(?:社内|内部)(?:で)?検討|交渉シミュレーション|第三者ジャッジ|"
        r"裁定(?:結果|を受けて|では|により|を踏まえ)|"
        r"案から(?:変更|修正|整理)(?:しました|しております)?|"
        r"[^。\n]{0,40}ではなく[^。\n]{0,40}(?:に|と)整理(?:しました|しております)?|"
        r"のまま維持(?:させてください|します|しました)?)"
    ),
    "LEGAL": re.compile(
        r"(?:法的(?:に|な)問題(?:は)?(?:ない|ありません|ございません)|"
        r"このまま(?:締結|提出)(?:(?:して)?差し支え(?:は)?(?:ない|ありません)|でき(?:ます)?|可能)|"
        r"このままご?締結いただいて構いません|"
        r"必ず(?:適法|有効))"
    ),
}


def find_comment_violations(comments: Iterable[str]) -> list[CommentViolation]:
    """M8/M13/LEGALの禁止語を全コメントで検査する。"""
    violations: list[CommentViolation] = []
    for index, comment in enumerate(comments):
        for code, pattern in _COMMENT_FORBIDDEN.items():
            match = pattern.search(comment or "")
            if match:
                violations.append(CommentViolation(index, code, match.group(0)))
    return violations


def build_negotiation_sim_block(
    win_ratio: str = "",
    premises: str = "",
    counterpart_profile: str = "",
) -> str:
    """交渉シミュレーション（勝ち度合い・力関係/BATNA/防衛ライン・相手プロファイル）のプロンプト注入ブロックを組み立てる。"""
    lines = []
    if win_ratio and win_ratio.strip():
        lines.append(f"- 目標利益配分（自分:相手）: {win_ratio.strip()}")
    if premises and premises.strip():
        lines.append(f"- 力関係・BATNA・絶対防衛ライン: {premises.strip()}")
    if counterpart_profile and counterpart_profile.strip():
        lines.append(f"- 相手方担当者プロファイル（性格・地雷・意思決定）: {counterpart_profile.strip()}")
    if not lines:
        return ""
    body = "\n".join(lines)
    return (
        "\n## 交渉シミュレーション前提（5席モデル基準）\n"
        f"{body}\n"
        "- 上記配分と相手プロファイルを踏まえ、相手担当者がメンツを潰されず社内稟議を通せる範囲でこちらの急所を守る修正にすること（勝ちすぎ・決裂トリガーは厳禁）。\n"
    )
